glyph_t bm_font_glyph(uint16_t ch)
{
    glyph_t g;
    if (ch >= '0' && ch <= '9') {
        g.data = g_digit_data[ch - '0'];
        g.w = 8; g.h = 8;
        return g;
    }
    if (ch >= 0x20 && ch <= 0x7E) {
        g.data = g_ascii_data[ch - 0x20];
        g.w = 5; g.h = 7;
        return g;
    }
    g.data = g_missing_data;
    g.w = 8; g.h = 8;
    return g;
}

glyph_t bm_font_glyph_narrow(uint16_t ch)
{
    if (ch >= '0' && ch <= '9')
        return (glyph_t){ g_ascii_data[ch - 0x20], 5, 7 };
    return bm_font_glyph(ch);
}


/* UTF-8 逐字解码：ASCII 1 字节 / 中文 3 字节；中文查 16x16 字库，未收录回退占位。 */
glyph_t bm_font_glyph_utf8(const char **sp)
{
    const uint8_t *p = (const uint8_t *)*sp;
    uint32_t cp;
    uint16_t i;
    if (p[0] < 0x80) {
        cp = p[0]; (*sp) += 1;
        return bm_font_glyph((uint16_t)cp);
    }
    if ((p[0] & 0xE0) == 0xC0 && p[1]) {
        cp = (uint32_t)(((p[0] & 0x1Fu) << 6) | (p[1] & 0x3Fu)); (*sp) += 2;
    } else if ((p[0] & 0xF0) == 0xE0 && p[1] && p[2]) {
        cp = (uint32_t)(((p[0] & 0x0Fu) << 12) | ((p[1] & 0x3Fu) << 6) | (p[2] & 0x3Fu));
        (*sp) += 3;
    } else { cp = (uint32_t)'?'; (*sp) += 1; }
    for (i = 0; i < (uint16_t)(sizeof(g_hz_codes) / sizeof(g_hz_codes[0])); i++) {
        if (g_hz_codes[i] == (uint16_t)cp)
            return (glyph_t){ g_hz_data[i], 16, 16 };
    }
    return (glyph_t){ g_missing_data, 8, 8 };
}
uint16_t bm_text_width(const char *s, uint8_t scale)
{
    uint16_t w = 0;
    uint8_t n = 0;
    while (*s) {
        glyph_t g = bm_font_glyph_utf8(&s);
        uint8_t gs = (g.w == 16) ? 1 : scale;   /* 中文 16x16 不放大 */
        w += (uint16_t)g.w * gs + gs;
        n++;
    }
    if (n > 0) w -= scale;
    return w;
}
