/* ---- 未知字符占位方块 ---- */
static const uint8_t g_missing_data[8] = {0x00,0x7E,0x7E,0x7E,0x7E,0x7E,0x7E,0x00};

glyph_t bm_font_glyph(uint16_t ch)
{
    glyph_t g;
    if (ch >= '0' && ch <= '9') {
        g.data = g_digit_data[ch - '0'];
        g.w = 8; g.h = 8;
        return g;
    }
    if (ch >= 0x20 && ch <= 0x7E) {
        g.data = g_ascii_data[ch - 0x20];
        g.w = 5; g.h = 7;
        return g;
    }
    g.data = g_missing_data;
    g.w = 8; g.h = 8;
    return g;
}

glyph_t bm_font_glyph_narrow(uint16_t ch)
{
    if (ch >= '0' && ch <= '9')
        return (glyph_t){ g_ascii_data[ch - 0x20], 5, 7 };
    return bm_font_glyph(ch);
}

uint16_t bm_text_width(const char *s, uint8_t scale)
{
    uint16_t w = 0;
    uint8_t n = 0;
    while (*s) {
        glyph_t g = bm_font_glyph((uint8_t)*s++);
        w += (uint16_t)g.w * scale + scale;
        n++;
    }
    if (n > 0) w -= scale;
    return w;
}
